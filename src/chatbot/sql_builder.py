"""Build T-SQL from a validated intent. No LLM is involved.

What: two builders, both returning a BuiltQuery: parameterized SQL, its parameter
values, and a readable copy with the values filled in.
    build_sql(intent)                       stereotypeSearch: one view
    build_relationship_sql(intent, plan)    relationship: the planner's route, joined through t_connector

How: names come from the metadata, values become @p1, @p2 ... parameters, and the
statement is assembled from a fixed template:
    SELECT <columns> FROM <view> WHERE <conditions AND-ed> ORDER BY <identifier>, <primary key>
For a relationship, each hop of the plan adds two joins (the connector, then the
next view), and the SELECT lists every stereotype's identifier along the route
followed by the target's columns; see build_relationship_sql.

Safety rules:
  * View and column names come only from metadata and are always bracket-quoted.
    Brackets are needed even for plain names: PROC is a T-SQL reserved word.
  * Every user value is a parameter (@p1, @p2, ...), never part of the SQL text.
  * LIKE wildcards typed by the user (% _ [) are escaped, so they match literally.
  * Every query has a stable ORDER BY (identifier column, then primary key).

The output also includes a readable version with the values filled in, for
manual review only. It must never be executed by code.

Why: SQL generated by an LLM can't be trusted or tested. Building it in code
from a validated intent means the same question always gives the same safe SQL.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from .intent import Filter, RelationshipIntent, StereotypeSearchIntent
from .planner import FORWARD, Plan

# t_connector holds every link drawn in EA. Its name and columns are the same for every
# relationship, so they live here rather than in relationships.json.
CONNECTOR_TABLE = "t_connector"
CONNECTOR_START = "Start_Object_ID"  # the object the link was drawn from
CONNECTOR_END = "End_Object_ID"  # the object the link was drawn to
CONNECTOR_TYPE = "Connector_Type"  # e.g. Dependency; the value to follow comes from relationships.json


@dataclass(frozen=True)
class BuiltQuery:
    """The builder's output. Only sql + params are ever executed; readable_sql is for people."""
    sql: str  # parameterized SQL, e.g. ... WHERE [Name] = @p1
    params: dict[str, object]  # {"@p1": "SREQ123"}
    readable_sql: str  # values inlined, for people to read and run by hand


def quote_identifier(name: str) -> str:
    """[Name] for a column, [SREQ] for a view. A ']' inside the name is doubled, as T-SQL requires."""
    return "[" + name.replace("]", "]]") + "]"


def escape_like(value: str) -> str:
    """Make %, _ and [ match literally inside a T-SQL LIKE pattern.

    Each one is wrapped in [...]. "[" is escaped first, because the other two
    replacements add "[" characters that must not be escaped again.
    """
    return value.replace("[", "[[]").replace("%", "[%]").replace("_", "[_]")


class _Params:
    """Collects parameter values for one query and hands out their names (@p1, @p2, ...).

    A new _Params is created per query, so numbering always starts at @p1 and two
    users' queries never share parameters.
    """
    def __init__(self) -> None:
        """Start with no parameters."""
        self.values: dict[str, object] = {}

    def add(self, value: object) -> str:
        """Store `value` and return its placeholder name; only the name goes into the SQL text."""
        name = f"@p{len(self.values) + 1}"
        self.values[name] = value
        return name


def build_sql(intent: StereotypeSearchIntent) -> BuiltQuery:
    """Turn a validated intent into SQL.

    SELECT lists [column] AS NAME for each requested attribute. WHERE is the
    identifier match for a lookup, or one condition per filter for a search, joined
    with AND (every filter must match). ORDER BY makes the row order the same on
    every run. The same _Params is passed to every condition so numbering continues.
    """
    st = intent.stereotype
    params = _Params()

    select = ",\n       ".join(f"{quote_identifier(a.column)} AS {a.name}" for a in intent.columns)

    if intent.is_lookup:
        conditions = [f"{quote_identifier(st.identifier_attribute.column)} = {params.add(intent.identifier)}"]
    else:
        conditions = [_condition(f, params) for f in intent.filters]

    sql = (
        f"SELECT {select}\n"
        f"FROM {quote_identifier(st.view)}\n"
        f"WHERE {' AND '.join(conditions)}\n"
        f"ORDER BY {quote_identifier(st.identifier_attribute.column)}, {quote_identifier(st.primary_key_column)};"
    )
    return BuiltQuery(sql=sql, params=params.values, readable_sql=_inline(sql, params.values))


def build_relationship_sql(intent: RelationshipIntent, plan: Plan) -> BuiltQuery:
    """Turn a validated relationship intent and its plan into SQL.

    Aliases are by position along the route: s0 is the question's source, s1 the next
    stereotype, ... sN the target; c1 ... cN are the connectors between them. Position,
    not stereotype code, so a route could visit the same view twice without a clash.

    Each hop adds two joins. Forward (walking the way the link was drawn):
        JOIN [t_connector] c1 ON c1.[Start_Object_ID] = s0.[Object_ID] AND c1.[Connector_Type] = 'Dependency'
        JOIN [USTP] s1        ON s1.[Object_ID] = c1.[End_Object_ID]
    Backward swaps Start and End. The Connector_Type condition (the relationship's
    connectorType) keeps only the links that mean this relationship. Every join is
    INNER: a row is returned only if it reaches the target.

    SELECT lists each stereotype's identifier in route order (UC_TAG, USTP_TAG, ...),
    then the target's other columns (DATA_DESCRIPTION, ...). No DISTINCT: with the
    Connector_Type filter, two objects are linked by at most one connector, so every
    row is a different combination of objects. The anchor is matched on s0; each
    filter on the alias of its stereotype (s0 or sN). ORDER BY is the identifier
    columns in route order; identifiers are unique per stereotype, so the order is stable.

    TODO(include): stereotypes shown alongside the route will be added here. Ones on
    the route only add columns; ones past the target become LEFT-joined branches from
    the target. See the TODO in intent.py for the planned rules.
    """
    params = _Params()
    stereotypes = plan.stereotypes
    last = len(stereotypes) - 1
    aliases = {0: "s0", last: f"s{last}"}

    tags = _unique_names([f"{st.code}_{st.identifier_attribute.name}" for st in stereotypes])
    select = [f"s{i}.{quote_identifier(st.identifier_attribute.column)} AS {tags[i]}" for i, st in enumerate(stereotypes)]
    target = stereotypes[last]
    for attr in intent.columns:
        if attr != target.identifier_attribute:
            select.append(f"s{last}.{quote_identifier(attr.column)} AS {target.code}_{attr.name}")

    lines = [f"FROM {quote_identifier(stereotypes[0].view)} s0"]
    for i, hop in enumerate(plan.hops, start=1):
        here, there = (CONNECTOR_START, CONNECTOR_END) if hop.direction == FORWARD else (CONNECTOR_END, CONNECTOR_START)
        prev, nxt = hop.from_stereotype, hop.to_stereotype
        lines.append(
            f"JOIN {quote_identifier(CONNECTOR_TABLE)} c{i} "
            f"ON c{i}.{quote_identifier(here)} = s{i - 1}.{quote_identifier(prev.primary_key_column)} "
            # connector_type is checked at startup (letters and spaces only), so it is safe as a literal.
            f"AND c{i}.{quote_identifier(CONNECTOR_TYPE)} = '{hop.relationship.connector_type}'"
        )
        lines.append(
            f"JOIN {quote_identifier(nxt.view)} s{i} "
            f"ON s{i}.{quote_identifier(nxt.primary_key_column)} = c{i}.{quote_identifier(there)}"
        )

    conditions = []
    if intent.identifier is not None:
        conditions.append(
            f"s0.{quote_identifier(intent.source.identifier_attribute.column)} = {params.add(intent.identifier)}"
        )
    for rf in intent.filters:
        alias = aliases[0] if rf.stereotype.code == intent.source.code else aliases[last]
        conditions.append(_condition(rf.filter, params, alias))

    sql = (
        "SELECT " + ",\n       ".join(select) + "\n"
        + "\n".join(lines) + "\n"
        + f"WHERE {' AND '.join(conditions)}\n"
        + f"ORDER BY {', '.join(tags)};"
    )
    return BuiltQuery(sql=sql, params=params.values, readable_sql=_inline(sql, params.values))


def _unique_names(names: list[str]) -> list[str]:
    """Make column aliases unique: a stereotype seen a second time on the route gets _2, then _3, ..."""
    seen: dict[str, int] = {}
    result = []
    for name in names:
        seen[name] = seen.get(name, 0) + 1
        result.append(name if seen[name] == 1 else f"{name}_{seen[name]}")
    return result


def _condition(f: Filter, params: _Params, alias: str | None = None) -> str:
    """Turn one Filter into one SQL condition string.

    alias (relationship queries only) prefixes the column, e.g. s3.[Note]; stereotype
    searches pass none, so their SQL is unchanged.
    EQUALS -> [col] = @pN (converted to int for number attributes).
    CONTAINS_ANY / CONTAINS_ALL -> ([col] LIKE @p1 OR/AND [col] LIKE @p2 ...), in
    parentheses so it combines correctly with the other filters' AND.
    An operator with no branch here raises NotImplementedError rather than being
    skipped, because skipping a filter would silently return too many rows.
    """
    column = quote_identifier(f.attribute.column)
    if alias:  # relationship queries join several views, so the column needs its view's alias
        column = f"{alias}.{column}"
    op = f.operator.name

    if op == "EQUALS":
        value: object = int(f.values[0]) if f.attribute.data_type == "number" else f.values[0]
        return f"{column} = {params.add(value)}"
    if op in ("CONTAINS_ANY", "CONTAINS_ALL"):
        parts = [f"{column} LIKE {params.add('%' + escape_like(v) + '%')}" for v in f.values]
        joiner = " OR " if op == "CONTAINS_ANY" else " AND "
        return "(" + joiner.join(parts) + ")"
    # Reaching here means operators.json lists an operator with no builder code.
    raise NotImplementedError(f"No SQL handler for operator {op}")


def _literal(value: object) -> str:
    """Write one parameter value as SQL text, for readable_sql only.

    Numbers as they are; strings as '...' with every ' doubled, so the
    readable version is still safe to paste into SSMS.
    """
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def _inline(sql: str, params: dict[str, object]) -> str:
    """Replace @pN with literals in one pass, so a value containing '@p2' is never re-replaced.

    Produces readable_sql, marked "for review only" on its first line.
    """
    out = re.sub(r"@p[0-9]+", lambda m: _literal(params[m.group(0)]), sql)
    return "-- For review only. Values are inlined; the application runs the parameterized version.\n" + out
