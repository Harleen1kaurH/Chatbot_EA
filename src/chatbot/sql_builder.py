"""Build T-SQL from a validated StereotypeSearchIntent. No LLM is involved.

What: build_sql() returns a BuiltQuery: parameterized SQL, its parameter values,
and a readable copy with the values filled in.

How: names come from the metadata, values become @p1, @p2 ... parameters, and the
statement is assembled from a fixed template:
    SELECT <columns> FROM <view> WHERE <conditions AND-ed> ORDER BY <identifier>, <primary key>

Safety rules:
  * View and column names come only from metadata and are always bracket-quoted.
    Brackets are needed even for plain names: PROC is a T-SQL reserved word.
  * Every user value is a parameter (@p1, @p2, ...), never part of the SQL text.
  * LIKE wildcards typed by the user (% _ [) are escaped, so they match literally.
  * Every query has a stable ORDER BY (identifier column, then primary key).

The output also includes a readable version with the values filled in, for
manual review only. It must never be executed by code.

Why: SQL generated by an LLM can't be trusted or tested. Building it in code
from a validated intent means the same question always gives the same safe SQL.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from .intent import Filter, StereotypeSearchIntent


@dataclass(frozen=True)
class BuiltQuery:
    """The builder's output. Only sql + params are ever executed; readable_sql is for people."""
    sql: str  # parameterized SQL, e.g. ... WHERE [Name] = @p1
    params: dict[str, object]  # {"@p1": "SREQ123"}
    readable_sql: str  # values inlined, for people to read and run by hand


def quote_identifier(name: str) -> str:
    """[Name] for a column, [SREQ] for a view. A ']' inside the name is doubled, as T-SQL requires."""
    return "[" + name.replace("]", "]]") + "]"


def escape_like(value: str) -> str:
    """Make %, _ and [ match literally inside a T-SQL LIKE pattern.

    Each one is wrapped in [...]. "[" is escaped first, because the other two
    replacements add "[" characters that must not be escaped again.
    """
    return value.replace("[", "[[]").replace("%", "[%]").replace("_", "[_]")


class _Params:
    """Collects parameter values for one query and hands out their names (@p1, @p2, ...).

    A new _Params is created per query, so numbering always starts at @p1 and two
    users' queries never share parameters.
    """
    def __init__(self) -> None:
        """Start with no parameters."""
        self.values: dict[str, object] = {}

    def add(self, value: object) -> str:
        """Store `value` and return its placeholder name; only the name goes into the SQL text."""
        name = f"@p{len(self.values) + 1}"
        self.values[name] = value
        return name


def build_sql(intent: StereotypeSearchIntent) -> BuiltQuery:
    """Turn a validated intent into SQL.

    SELECT lists [column] AS NAME for each requested attribute. WHERE is the
    identifier match for a lookup, or one condition per filter for a search, joined
    with AND (every filter must match). ORDER BY makes the row order the same on
    every run. The same _Params is passed to every condition so numbering continues.
    """
    st = intent.stereotype
    params = _Params()

    select = ",\n       ".join(f"{quote_identifier(a.column)} AS {a.name}" for a in intent.columns)

    if intent.is_lookup:
        conditions = [f"{quote_identifier(st.identifier_attribute.column)} = {params.add(intent.identifier)}"]
    else:
        conditions = [_condition(f, params) for f in intent.filters]

    sql = (
        f"SELECT {select}\n"
        f"FROM {quote_identifier(st.view)}\n"
        f"WHERE {' AND '.join(conditions)}\n"
        f"ORDER BY {quote_identifier(st.identifier_attribute.column)}, {quote_identifier(st.primary_key_column)};"
    )
    return BuiltQuery(sql=sql, params=params.values, readable_sql=_inline(sql, params.values))


def _condition(f: Filter, params: _Params) -> str:
    """Turn one Filter into one SQL condition string.

    EQUALS -> [col] = @pN (converted to int for number attributes).
    CONTAINS_ANY / CONTAINS_ALL -> ([col] LIKE @p1 OR/AND [col] LIKE @p2 ...), in
    parentheses so it combines correctly with the other filters' AND.
    An operator with no branch here raises NotImplementedError rather than being
    skipped, because skipping a filter would silently return too many rows.
    """
    column = quote_identifier(f.attribute.column)
    op = f.operator.name

    if op == "EQUALS":
        value: object = int(f.values[0]) if f.attribute.data_type == "number" else f.values[0]
        return f"{column} = {params.add(value)}"
    if op in ("CONTAINS_ANY", "CONTAINS_ALL"):
        parts = [f"{column} LIKE {params.add('%' + escape_like(v) + '%')}" for v in f.values]
        joiner = " OR " if op == "CONTAINS_ANY" else " AND "
        return "(" + joiner.join(parts) + ")"
    # Reaching here means operators.json lists an operator with no builder code.
    raise NotImplementedError(f"No SQL handler for operator {op}")


def _literal(value: object) -> str:
    """Write one parameter value as SQL text, for readable_sql only.

    Numbers as they are; strings as '...' with every ' doubled, so the
    readable version is still safe to paste into SSMS.
    """
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def _inline(sql: str, params: dict[str, object]) -> str:
    """Replace @pN with literals in one pass, so a value containing '@p2' is never re-replaced.

    Produces readable_sql, marked "for review only" on its first line.
    """
    out = re.sub(r"@p[0-9]+", lambda m: _literal(params[m.group(0)]), sql)
    return "-- For review only. Values are inlined; the application runs the parameterized version.\n" + out
